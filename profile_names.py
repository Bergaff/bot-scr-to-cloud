def _seed(*parts) -> int:
    return int(hashlib.sha256("|".join(str(p) for p in parts).encode("utf-8")).hexdigest(), 16)


def pick_name(seed_value, taken: set[str] | None = None) -> tuple[str, str]:
    """(имя, фамилия) для аккаунта; не повторяет уже занятые полные имена из taken."""
    taken = {t.strip().lower() for t in (taken or set())}
    for attempt in range(200):
        number = _seed(seed_value, attempt)
        female = number % 2 == 1
        first = (FEMALE if female else MALE)[(number // 2) % 30]
        male_sur, female_sur = SURNAMES[(number // 60) % len(SURNAMES)]
        last = female_sur if female else male_sur
        if f"{first} {last}".lower() not in taken:
            return first, last
    return first, last


def split_name(full: str) -> tuple[str, str]:
    """«Имя Фамилия» -> (имя, фамилия); одно слово — только имя."""
    parts = (full or "").split(None, 1)
    return (parts[0] if parts else ""), (parts[1].strip() if len(parts) > 1 else "")
